// Derives latency-table.txt from the three bench runs in results/, so the table
// cannot drift from its evidence. verify-all.sh regenerates it and fails if the
// committed copy differs by a byte.
import fs from 'node:fs';

const CLIENTS = [
  ['Playwright / CDP', /^Playwright\s+CDP/],
  ['Puppeteer / CDP', /^Puppeteer\s+CDP/],
  ['Selenium / WebDriver Classic', /^Selenium\s+WebDriver Classic/],
  ['raw client / WebDriver BiDi', /^raw client WebDriver BiDi/],
];

// rtt0 columns: IMPORT CLIENT BROWSER PROCS CPU WALK MSGS EVAL ITEMS
// rtt20/60:     IMPORT CLIENT BROWSER PROCS     WALK MSGS EVAL MSGS ITEMS
const parse = (file, hasCpu) => {
  const out = {};
  for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
    for (const [name, re] of CLIENTS) {
      if (!re.test(line)) continue;
      const ms = [...line.matchAll(/([\d.]+)\s*ms/g)].map((m) => +m[1]);
      const ints = [...line.matchAll(/\s(\d{1,4})\s/g)].map((m) => +m[1]);
      const walk = ms[0], evalMs = ms[1];
      // message count is the integer sitting between walk and eval on the line
      const wi = line.indexOf(`${walk} ms`) + `${walk} ms`.length;
      const ei = line.indexOf(`${evalMs} ms`, wi);
      const msgs = +(line.slice(wi, ei).match(/(\d+)/) || [])[1];
      const after = line.slice(ei + String(evalMs).length + 3); // skip past the eval ms token itself
      const evalMsgs = hasCpu ? null : +(after.match(/(\d+)/) || [])[1];
      out[name] = { walk, msgs, evalMs, evalMsgs };
    }
  }
  return out;
};

const r0 = parse('results/out-rtt0.txt', true);
const r20 = parse('results/out-rtt20.txt', false);
const r60 = parse('results/out-rtt60.txt', false);

const pad = (s, n) => String(s).padEnd(n);
const rp = (s, n) => String(s).padStart(n);

let L = [];
L.push(pad('CLIENT', 34) + rp('MSGS', 8) + rp('RTT 0ms', 12) + rp('RTT 20ms', 12) + rp('RTT 60ms', 12));
L.push('-'.repeat(76));
L.push('  20 cards read one locator at a time');
for (const [name] of CLIENTS) {
  const m = [...new Set([r0[name].msgs, r20[name].msgs, r60[name].msgs])].sort((a, b) => a - b);
  L.push('    ' + pad(name, 30) + rp(m.length === 1 ? m[0] : `${m[0]}-${m[m.length - 1]}`, 8)
    + rp(`${r0[name].walk} ms`, 12) + rp(`${r20[name].walk} ms`, 12) + rp(`${r60[name].walk} ms`, 12));
}
L.push('');
L.push('  the same 20 cards read in one evaluation');
for (const [name] of CLIENTS) {
  const m = [...new Set([r20[name].evalMsgs, r60[name].evalMsgs].filter(Boolean))].sort((a, b) => a - b);
  L.push('    ' + pad(name, 30) + rp(m.length === 1 ? m[0] : `${m[0]}-${m[m.length - 1]}`, 8)
    + rp(`${r0[name].evalMs} ms`, 12) + rp(`${r20[name].evalMs} ms`, 12) + rp(`${r60[name].evalMs} ms`, 12));
}
L.push('');
L.push('RTT is injected between the automation client and the browser, on both legs.');
L.push('Generated by make-latency-table.mjs from out-rtt0.txt, out-rtt20.txt and out-rtt60.txt.');

fs.writeFileSync('latency-table.txt', L.join('\n') + '\n');
